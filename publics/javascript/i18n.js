(function () {
  function getPreferredLanguage() {
    const saved = localStorage.getItem('aetheria_lang');
    if (saved && (saved === 'id' || saved === 'en')) return saved;
    // Default to 'id'
    return 'id';
  }

  let currentLang = getPreferredLanguage();

  function t(key) {
    const dict = AETHERIA_TRANSLATIONS[currentLang] || AETHERIA_TRANSLATIONS.id;
    return dict[key] || AETHERIA_TRANSLATIONS.id[key] || key;
  }

  function applyLanguage(lang) {
    if (lang !== 'id' && lang !== 'en') lang = 'id';
    currentLang = lang;
    document.documentElement.lang = lang;
    localStorage.setItem('aetheria_lang', lang);

    // 1. Text elements
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (key) {
        const text = t(key);
        if (text) el.innerText = text;
      }
    });

    // 2. HTML elements
    document.querySelectorAll('[data-i18n-html]').forEach(el => {
      const key = el.getAttribute('data-i18n-html');
      if (key) {
        const html = t(key);
        if (html) el.innerHTML = html;
      }
    });

    // 3. Placeholders
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      if (key) {
        const val = t(key);
        if (val) el.setAttribute('placeholder', val);
      }
    });

    // 4. Update toggle buttons
    updateLanguageButtons(lang);

    // 5. Dispatch event for dynamic handlers
    window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang, t } }));
  }

  function updateLanguageButtons(lang) {
    const btns = document.querySelectorAll('.lang-toggle-btn, #langToggleBtn');
    btns.forEach(btn => {
      if (lang === 'en') {
        btn.innerHTML = `<span class="lang-toggle-badge bg-rose-600 text-white">EN</span> <span class="hidden sm:inline ml-1 text-xs text-slate-300">English</span>`;
        btn.setAttribute('title', 'Ganti ke Bahasa Indonesia');
      } else {
        btn.innerHTML = `<span class="lang-toggle-badge bg-emerald-600 text-white">ID</span> <span class="hidden sm:inline ml-1 text-xs text-slate-300">Indonesia</span>`;
        btn.setAttribute('title', 'Switch to English');
      }
    });
  }

  window.setLanguage = applyLanguage;

  window.toggleLanguage = function () {
    const next = currentLang === 'id' ? 'en' : 'id';
    applyLanguage(next);
  };

  window.t = t;

  document.addEventListener('DOMContentLoaded', () => {
    applyLanguage(currentLang);
  });
})();
